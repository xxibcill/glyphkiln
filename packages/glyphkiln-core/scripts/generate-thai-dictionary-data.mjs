// Generates src/typography/thai-dictionary.generated.ts from the vendored,
// hash-checked ICU 78.3 thaidict.txt (Unicode-3.0), for policy
// thai-segmentation-hybrid@1.0.0. --verify fails when the committed module is
// stale.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import prettier from "prettier";

const root = new URL("../", import.meta.url);
const sourceDirectory = new URL("vendor/icu/78.3/", root);
const checksums = JSON.parse(
  await readFile(new URL("source-checksums.json", sourceDirectory), "utf8"),
);
const outputUrl = new URL("src/typography/thai-dictionary.generated.ts", root);

const bytes = await readFile(new URL("thaidict.txt", sourceDirectory));
const sourceSha256 = createHash("sha256").update(bytes).digest("hex");
if (sourceSha256 !== checksums.files["thaidict.txt"]) {
  throw new Error(`thaidict.txt checksum mismatch: ${sourceSha256}`);
}

const THAI_WORD = /^[\u0e01-\u0e5b]+$/u;
const words = new Set();
for (const [index, rawLine] of bytes
  .toString("utf8")
  .replace(/^\uFEFF/u, "")
  .split("\n")
  .entries()) {
  const line = rawLine.trim();
  if (line.length === 0 || line.startsWith("#")) continue;
  if (!THAI_WORD.test(line) || line.normalize("NFC") !== line) {
    throw new Error(`thaidict.txt:${index + 1} is not a Thai NFC word`);
  }
  words.add(line);
}
// Code-unit order: independent of the host's collation.
const sorted = [...words].sort((left, right) =>
  left < right ? -1 : left > right ? 1 : 0,
);
const joined = sorted.join("\n");
const wordsSha256 = createHash("sha256").update(joined).digest("hex");
const maxLength = Math.max(...sorted.map((word) => word.length));

const module = `// Generated by scripts/generate-thai-dictionary-data.mjs. Do not edit.
// ICU ${checksums.icuVersion} thaidict.txt (${checksums.tag}, commit ${checksums.commit}).
// Copyright (C) 2016 and later: Unicode, Inc. and others. Copyright (c)
// 2006-2015 International Business Machines Corporation, Apple Inc., and
// others. Licensed under the Unicode License v3 (Unicode-3.0); see
// vendor/icu/LICENSE.

export const THAI_DICTIONARY_SOURCE = Object.freeze({
  name: "icu-thaidict",
  icuVersion: ${JSON.stringify(checksums.icuVersion)},
  tag: ${JSON.stringify(checksums.tag)},
  commit: ${JSON.stringify(checksums.commit)},
  license: "Unicode-3.0",
  sourceSha256: ${JSON.stringify(sourceSha256)},
  wordsSha256: ${JSON.stringify(wordsSha256)},
  wordCount: ${sorted.length},
  maxWordLength: ${maxLength},
});

/** The dictionary words, NFC, in code-unit order, joined by "\\n". */
// prettier-ignore
export const THAI_DICTIONARY_WORDS = ${JSON.stringify(joined)};
`;
const prettierOptions = (await prettier.resolveConfig(outputUrl.pathname)) ?? {};
const formatted = await prettier.format(module, {
  ...prettierOptions,
  parser: "typescript",
});
if (process.argv.includes("--verify")) {
  const committed = await readFile(outputUrl, "utf8");
  if (committed !== formatted) {
    throw new Error(
      "thai-dictionary.generated.ts is stale; run npm run text-layout-data:update",
    );
  }
  process.stdout.write(`Verified ICU thaidict data (${sorted.length} words).\n`);
} else {
  await writeFile(outputUrl, formatted, "utf8");
  process.stdout.write(`Wrote ICU thaidict data (${sorted.length} words).\n`);
}
