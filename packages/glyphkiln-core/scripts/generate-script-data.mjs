// Generates src/typography/script-data.generated.ts from the vendored,
// hash-checked Unicode 17.0.0 Scripts.txt (policy script-runs@1.0.0).
// --verify fails when the committed module is stale.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import prettier from "prettier";

const root = new URL("../", import.meta.url);
const sourceUrl = new URL("vendor/unicode/17.0.0/sources/Scripts.txt", root);
const checksumsUrl = new URL("vendor/unicode/17.0.0/source-checksums.json", root);
const outputUrl = new URL("src/typography/script-data.generated.ts", root);

const checksums = JSON.parse(await readFile(checksumsUrl, "utf8"));
const source = await readFile(sourceUrl, "utf8");
const actual = createHash("sha256").update(source).digest("hex");
if (actual !== checksums.files["Scripts.txt"]) {
  throw new Error(`Scripts.txt checksum mismatch: ${actual}`);
}

const ranges = [];
for (const [index, rawLine] of source.split(/\r?\n/).entries()) {
  const line = rawLine.split("#", 1)[0].trim();
  if (line.length === 0) continue;
  const [range, script] = line.split(";").map((part) => part.trim());
  const match = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?$/.exec(range ?? "");
  if (match === null || script === undefined || script.length === 0) {
    throw new Error(`Scripts.txt:${index + 1} is malformed`);
  }
  ranges.push([
    Number.parseInt(match[1], 16),
    Number.parseInt(match[2] ?? match[1], 16),
    script,
  ]);
}
ranges.sort((left, right) => left[0] - right[0]);
const names = [...new Set(ranges.map(([, , script]) => script))].sort();
const merged = [];
for (const [start, end, script] of ranges) {
  const previous = merged.at(-1);
  if (previous !== undefined && start <= previous[1]) {
    throw new Error(`Scripts.txt ranges overlap at ${start.toString(16)}`);
  }
  const scriptIndex = names.indexOf(script);
  if (
    previous !== undefined &&
    previous[2] === scriptIndex &&
    start === previous[1] + 1
  ) {
    previous[1] = end;
  } else {
    merged.push([start, end, scriptIndex]);
  }
}

const hex = (value) => `0x${value.toString(16).toUpperCase()}`;
const module = `/* This file is generated by scripts/generate-script-data.mjs. */

export const SCRIPT_DATA_UNICODE_VERSION = "17.0.0" as const;
export const SCRIPT_DATA_SOURCE_SHA256 = "${actual}" as const;

/** Unicode Script property values (long names), sorted. */
export const SCRIPT_NAMES: readonly string[] = Object.freeze(${JSON.stringify(names)});

/** Sorted, non-overlapping [start, end, index into SCRIPT_NAMES]. Unlisted code points are Unknown. */
export const SCRIPT_RANGES: readonly (readonly [number, number, number])[] = Object.freeze([
${merged.map(([start, end, index]) => `  [${hex(start)}, ${hex(end)}, ${index}],`).join("\n")}
]);
`;
const prettierOptions = (await prettier.resolveConfig(outputUrl.pathname)) ?? {};
const formatted = await prettier.format(module, {
  ...prettierOptions,
  parser: "typescript",
});
if (process.argv.includes("--verify")) {
  const committed = await readFile(outputUrl, "utf8");
  if (committed !== formatted) {
    throw new Error(
      "script-data.generated.ts is stale; run npm run text-layout-data:update",
    );
  }
  process.stdout.write(
    `Verified Unicode 17.0.0 script data (${merged.length} ranges).\n`,
  );
} else {
  await writeFile(outputUrl, formatted, "utf8");
  process.stdout.write(`Wrote Unicode 17.0.0 script data (${merged.length} ranges).\n`);
}
