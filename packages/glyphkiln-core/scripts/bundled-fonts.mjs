// Verifies (default) or regenerates (--write) the bundled-font contract:
// assets/fonts/catalog.json is the admission record, every file under
// assets/fonts must be listed in it (or be the Inter development font) with
// the exact SHA-256 and size, each family ships its OFL text, and
// src/fonts/bundled-catalog.generated.ts is the pinned table Core reads.
import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { relative } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = new URL("../", import.meta.url);
const fontsRoot = new URL("assets/fonts/", packageRoot);
const generatedUrl = new URL("src/fonts/bundled-catalog.generated.ts", packageRoot);
const DEVELOPMENT_FILES = new Map([
  [
    "Inter-Variable.ttf",
    "29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031",
  ],
  ["OFL.txt", undefined],
  ["catalog.json", undefined],
]);

export async function verifyBundledFonts({ write = false } = {}) {
  const catalog = JSON.parse(
    await readFile(new URL("catalog.json", fontsRoot), "utf8"),
  );
  if (catalog.schemaVersion !== "1.0.0")
    throw new Error("Unknown font catalog schema.");
  const listed = new Map();
  const families = new Set();
  for (const family of catalog.families) {
    if (families.has(family.family))
      throw new Error(`Duplicate family ${family.family}.`);
    families.add(family.family);
    if (family.license !== "OFL-1.1") {
      throw new Error(`${family.family} has unreviewed license ${family.license}.`);
    }
    listed.set(family.licenseFile, family.licenseSha256);
    const keys = new Set();
    for (const file of family.files) {
      if (!file.file.startsWith(`${family.directory}/`) || file.file.includes("..")) {
        throw new Error(`${file.file} is outside ${family.directory}/.`);
      }
      for (const weight of file.weights) {
        const key = `${file.style}/${weight}`;
        if (keys.has(key)) throw new Error(`${family.family} maps ${key} twice.`);
        keys.add(key);
      }
      listed.set(file.file, file.sha256);
      const bytes = await readFile(new URL(file.file, fontsRoot));
      if (bytes.length !== file.bytes) throw new Error(`${file.file} size changed.`);
    }
  }
  const onDisk = await listFiles(fontsRoot);
  for (const path of onDisk) {
    const bytes = await readFile(new URL(path, fontsRoot));
    const hash = createHash("sha256").update(bytes).digest("hex");
    if (DEVELOPMENT_FILES.has(path)) {
      const expected = DEVELOPMENT_FILES.get(path);
      if (expected !== undefined && expected !== hash) {
        throw new Error(`${path} does not match its pinned SHA-256.`);
      }
      continue;
    }
    if (!listed.has(path)) throw new Error(`${path} is not admitted in catalog.json.`);
    if (listed.get(path) !== hash)
      throw new Error(`${path} does not match catalog.json.`);
    listed.delete(path);
  }
  if (listed.size > 0) {
    throw new Error(
      `catalog.json lists missing files: ${[...listed.keys()].join(", ")}.`,
    );
  }
  const rendered = renderTable(catalog);
  if (write) {
    await writeFile(generatedUrl, rendered, "utf8");
  } else {
    const committed = await readFile(generatedUrl, "utf8");
    if (committed !== rendered) {
      throw new Error(
        "bundled-catalog.generated.ts is stale; run npm run licenses:update.",
      );
    }
  }
  return {
    families: catalog.families.length,
    files: catalog.families.reduce((sum, family) => sum + family.files.length, 0),
  };
}

async function listFiles(root) {
  const out = [];
  async function walk(url) {
    for (const entry of await readdir(url, { withFileTypes: true })) {
      const child = new URL(entry.isDirectory() ? `${entry.name}/` : entry.name, url);
      if (entry.isSymbolicLink()) throw new Error(`${entry.name} is a symlink.`);
      if (entry.isDirectory()) await walk(child);
      else if ((await stat(child)).isFile()) {
        out.push(
          relative(fileURLToPath(root), fileURLToPath(child)).split("\\").join("/"),
        );
      }
    }
  }
  await walk(root);
  return out.sort();
}

function renderTable(catalog) {
  const rows = [];
  for (const family of catalog.families) {
    for (const file of family.files) {
      rows.push(
        `  { family: ${JSON.stringify(family.family)}, style: ${JSON.stringify(file.style)}, weights: [${file.weights.join(", ")}], file: ${JSON.stringify(file.file)}, sha256: ${JSON.stringify(file.sha256)} },`,
      );
    }
  }
  const families = catalog.families.map(
    (family) =>
      `  { family: ${JSON.stringify(family.family)}, scripts: [${family.scripts.map((script) => JSON.stringify(script)).join(", ")}], license: "OFL-1.1", licenseFile: ${JSON.stringify(family.licenseFile)} },`,
  );
  return `// Generated by scripts/bundled-fonts.mjs from assets/fonts/catalog.json.
// Do not edit by hand: run npm run licenses:update.
// prettier-ignore
export const BUNDLED_FONT_SOURCE = ${JSON.stringify(`${catalog.source.repository}@${catalog.source.commit}/${catalog.source.path}`)} as const;

// prettier-ignore
export const BUNDLED_FONT_FAMILY_TABLE = [
${families.join("\n")}
] as const;

// prettier-ignore
export const BUNDLED_FONT_FILE_TABLE = [
${rows.join("\n")}
] as const;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await verifyBundledFonts({ write: process.argv.includes("--write") });
  process.stdout.write(
    `${process.argv.includes("--write") ? "Wrote" : "Verified"} ${result.files} bundled font files in ${result.families} families.\n`,
  );
}
