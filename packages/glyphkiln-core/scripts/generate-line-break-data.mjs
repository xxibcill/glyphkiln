// Generates src/typography/line-break-data.generated.ts from the vendored,
// hash-checked Unicode 17.0.0 LineBreak.txt, EastAsianWidth.txt,
// DerivedGeneralCategory.txt and emoji-data.txt (policy line-break-uax14@17.0.0).
// --verify fails when the committed module is stale.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import process from "node:process";
import prettier from "prettier";

const root = new URL("../", import.meta.url);
const sourceDirectory = new URL("vendor/unicode/17.0.0/sources/", root);
const checksumsUrl = new URL("vendor/unicode/17.0.0/source-checksums.json", root);
const outputUrl = new URL("src/typography/line-break-data.generated.ts", root);
const checksums = JSON.parse(await readFile(checksumsUrl, "utf8")).files;

const SOURCES = [
  "LineBreak.txt",
  "EastAsianWidth.txt",
  "DerivedGeneralCategory.txt",
  "emoji-data.txt",
];
const hashes = {};
const texts = {};
for (const name of SOURCES) {
  const text = await readFile(new URL(name, sourceDirectory), "utf8");
  const actual = createHash("sha256").update(text).digest("hex");
  if (actual !== checksums[name]) {
    throw new Error(`${name} checksum mismatch: ${actual}`);
  }
  hashes[name] = actual;
  texts[name] = text;
}

const SIZE = 0x110000;
/** Visit every data line as (start, end, value), rejecting malformed lines. */
function* entries(name) {
  for (const [index, rawLine] of texts[name].split(/\r?\n/).entries()) {
    const line = rawLine.split("#", 1)[0].trim();
    if (line.length === 0) continue;
    const [range, value] = line.split(";").map((part) => part.trim());
    const match = /^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?$/.exec(range ?? "");
    if (match === null || value === undefined || value.length === 0) {
      throw new Error(`${name}:${index + 1} is malformed`);
    }
    yield [
      Number.parseInt(match[1], 16),
      Number.parseInt(match[2] ?? match[1], 16),
      value,
    ];
  }
}
function missingDefault(name) {
  const match = /^# @missing: 0000\.\.10FFFF; (\S+)$/m.exec(texts[name]);
  if (match === null) throw new Error(`${name} has no full-range @missing line`);
  return match[1];
}

// Line_Break classes; a full-range @missing default (XX) covers gaps.
const lineBreakDefault = missingDefault("LineBreak.txt");
const lineBreak = new Array(SIZE).fill(lineBreakDefault);
for (const [start, end, value] of entries("LineBreak.txt")) {
  for (let cp = start; cp <= end; cp += 1) lineBreak[cp] = value;
}
const CLASSES = [...new Set(lineBreak)].sort();
if (CLASSES.length > 64) throw new Error("Too many Line_Break classes");

const FLAG_EAST_ASIAN = 1 << 6; // East_Asian_Width F, W or H
const FLAG_PI = 1 << 7; // General_Category Pi
const FLAG_PF = 1 << 8; // General_Category Pf
const FLAG_MARK = 1 << 9; // General_Category Mn or Mc
const FLAG_PICTOGRAPHIC_UNASSIGNED = 1 << 10; // Extended_Pictographic and Cn

const flags = new Uint16Array(SIZE);
const eastAsianDefault = missingDefault("EastAsianWidth.txt");
if (!["N", "Na", "A"].includes(eastAsianDefault)) {
  throw new Error("Unexpected East_Asian_Width default");
}
for (const [start, end, value] of entries("EastAsianWidth.txt")) {
  if (value !== "F" && value !== "W" && value !== "H") continue;
  for (let cp = start; cp <= end; cp += 1) flags[cp] |= FLAG_EAST_ASIAN;
}
const assigned = new Uint8Array(SIZE);
for (const [start, end, value] of entries("DerivedGeneralCategory.txt")) {
  const flag =
    value === "Pi"
      ? FLAG_PI
      : value === "Pf"
        ? FLAG_PF
        : value === "Mn" || value === "Mc"
          ? FLAG_MARK
          : 0;
  for (let cp = start; cp <= end; cp += 1) {
    flags[cp] |= flag;
    if (value !== "Cn") assigned[cp] = 1;
  }
}
for (const [start, end, value] of entries("emoji-data.txt")) {
  if (value !== "Extended_Pictographic") continue;
  for (let cp = start; cp <= end; cp += 1) {
    if (assigned[cp] === 0) flags[cp] |= FLAG_PICTOGRAPHIC_UNASSIGNED;
  }
}

const ranges = [];
for (let cp = 0; cp < SIZE; cp += 1) {
  const value = CLASSES.indexOf(lineBreak[cp]) | flags[cp];
  const previous = ranges.at(-1);
  if (previous !== undefined && previous[1] === cp - 1 && previous[2] === value) {
    previous[1] = cp;
  } else {
    ranges.push([cp, cp, value]);
  }
}

const hex = (value) => `0x${value.toString(16).toUpperCase()}`;
const module = `/* This file is generated by scripts/generate-line-break-data.mjs. */

export const LINE_BREAK_DATA_UNICODE_VERSION = "17.0.0" as const;
export const LINE_BREAK_DATA_SOURCE_SHA256 = Object.freeze(${JSON.stringify(hashes)});

/** Line_Break property values (short names), sorted; a range value's low 6 bits index this. */
export const LINE_BREAK_CLASSES: readonly string[] = Object.freeze(${JSON.stringify(CLASSES)});

export const LINE_BREAK_FLAG_EAST_ASIAN = ${FLAG_EAST_ASIAN};
export const LINE_BREAK_FLAG_PI = ${FLAG_PI};
export const LINE_BREAK_FLAG_PF = ${FLAG_PF};
export const LINE_BREAK_FLAG_MARK = ${FLAG_MARK};
export const LINE_BREAK_FLAG_PICTOGRAPHIC_UNASSIGNED = ${FLAG_PICTOGRAPHIC_UNASSIGNED};

/** Starts of contiguous ranges covering U+0000..U+10FFFF, ascending. */
export const LINE_BREAK_RANGE_STARTS: readonly number[] = Object.freeze([
${ranges.map(([start]) => hex(start)).join(",")}
]);

/** Class index and flags of each range in LINE_BREAK_RANGE_STARTS. */
export const LINE_BREAK_RANGE_VALUES: readonly number[] = Object.freeze([
${ranges.map(([, , value]) => value).join(",")}
]);
`;
const prettierOptions = (await prettier.resolveConfig(outputUrl.pathname)) ?? {};
const formatted = await prettier.format(module, {
  ...prettierOptions,
  parser: "typescript",
});
if (process.argv.includes("--verify")) {
  const committed = await readFile(outputUrl, "utf8");
  if (committed !== formatted) {
    throw new Error(
      "line-break-data.generated.ts is stale; run npm run text-layout-data:update",
    );
  }
  process.stdout.write(
    `Verified Unicode 17.0.0 line-break data (${ranges.length} ranges).\n`,
  );
} else {
  await writeFile(outputUrl, formatted, "utf8");
  process.stdout.write(
    `Wrote Unicode 17.0.0 line-break data (${ranges.length} ranges).\n`,
  );
}
