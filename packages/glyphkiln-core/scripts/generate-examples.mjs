import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import process from "node:process";

import { renderGraphic } from "../dist/index.js";
import { loadExampleAssets } from "./example-assets.mjs";

const examples = [
  "product-announcement",
  "statistic-card",
  "quote-card",
  "article-cover",
  "tiktok-carousel-slide",
  "image-led-campaign",
];
const outputDirectory = resolve("examples/generated");
const verify = process.argv.includes("--verify");
const creationTimestamp = "2026-07-29T00:00:00.000Z";
await mkdir(outputDirectory, { recursive: true });

for (const name of examples) {
  const document = JSON.parse(await readFile(resolve(`examples/${name}.json`), "utf8"));
  const assets = await loadExampleAssets(document);
  const result = await renderGraphic(document, {
    formats: ["svg", "png"],
    creationTimestamp,
    assets,
  });
  for (const output of result.outputs) {
    const outputPath = resolve(outputDirectory, `${name}.${output.format}`);
    const manifest = `${JSON.stringify(output.manifest, null, 2)}\n`;
    if (verify) {
      const committedOutput = await readFile(outputPath);
      const committedManifest = await readFile(`${outputPath}.manifest.json`, "utf8");
      if (!committedOutput.equals(Buffer.from(output.bytes))) {
        throw new Error(`${basename(outputPath)} does not match generated bytes.`);
      }
      if (committedManifest !== manifest) {
        throw new Error(`${basename(outputPath)} manifest is stale.`);
      }
    } else {
      await writeFile(outputPath, output.bytes);
      await writeFile(`${outputPath}.manifest.json`, manifest, "utf8");
    }
    process.stdout.write(`${basename(outputPath)} ${output.manifest.output.sha256}\n`);
  }
}
